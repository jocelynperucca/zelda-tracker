// Turns the game CSV files in db/data/ into db/seed.sql.
//
//   node db/generate-seed.js      (or: npm run db:seed, which also loads it)
//
// CSV format (one row per item, rows in PLAYTHROUGH order):
//   location,type,name,hint,verified
// - location_no is assigned in the order each location FIRST appears
// - item_no counts up 1, 2, 3... within each game
// - sort_order counts up within each location
// Fields must not contain commas.

import { readFileSync, writeFileSync } from 'node:fs';

// Add game #2 here later, with its own CSV.
const GAMES = [
  { title: 'Ocarina of Time', shortName: 'OoT', year: 1998, console: 'Nintendo 64', csv: 'db/data/oot.csv' },
];

const ITEM_TYPES = [
  'Heart Piece', 'Heart Container', 'Bottle', 'Song',
  'Quest Item', 'Inventory Item', 'Equipment', 'Upgrade',
];

const sql = (v) => (v === null || v === '' ? 'NULL' : `'${String(v).replace(/'/g, "''")}'`);

const out = [
  '-- GENERATED by db/generate-seed.js. Edit the CSVs in db/data/, not this file.',
  'BEGIN;',
  'TRUNCATE user_items, items, locations, games, item_types RESTART IDENTITY CASCADE;',
  '',
];

ITEM_TYPES.forEach((t, i) => out.push(`INSERT INTO item_types (id, name) VALUES (${i + 1}, ${sql(t)});`));
out.push('');

GAMES.forEach((game, g) => {
  const gameId = g + 1;
  out.push(`-- ${game.title}`);
  out.push(`INSERT INTO games (id, title, short_name, release_year, console) VALUES (${gameId}, ${sql(game.title)}, ${sql(game.shortName)}, ${game.year}, ${sql(game.console)});`);

  const [header, ...rows] = readFileSync(game.csv, 'utf8').trim().split(/\r?\n/);
  const locations = new Map(); // name -> { no, count }
  let itemNo = 0;
  const itemLines = [];

  rows.forEach((line, r) => {
    const cols = line.split(',');
    if (cols.length !== 5) throw new Error(`${game.csv} line ${r + 2}: expected 5 columns, got ${cols.length}`);
    const [location, type, name, hint] = cols.map((c) => c.trim());

    const typeId = ITEM_TYPES.indexOf(type) + 1;
    if (!typeId) throw new Error(`${game.csv} line ${r + 2}: unknown type "${type}"`);

    if (!locations.has(location)) locations.set(location, { no: locations.size + 1, count: 0 });
    const loc = locations.get(location);
    loc.count += 1;
    itemNo += 1;

    itemLines.push(
      `INSERT INTO items (game_id, item_no, location_no, type_id, name, hint, sort_order) VALUES (${gameId}, ${itemNo}, ${loc.no}, ${typeId}, ${sql(name)}, ${sql(hint)}, ${loc.count});`
    );
  });

  for (const [name, loc] of locations) {
    out.push(`INSERT INTO locations (game_id, location_no, name) VALUES (${gameId}, ${loc.no}, ${sql(name)});`);
  }
  out.push(...itemLines, '');
  console.log(`${game.title}: ${locations.size} locations, ${itemNo} items`);
});

// Keep SERIAL counters in sync since we inserted explicit ids
out.push("SELECT setval('games_id_seq', (SELECT MAX(id) FROM games));");
out.push("SELECT setval('item_types_id_seq', (SELECT MAX(id) FROM item_types));");
out.push('COMMIT;');

writeFileSync('db/seed.sql', out.join('\n') + '\n');
console.log('Wrote db/seed.sql');
